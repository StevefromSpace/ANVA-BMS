import { Link } from 'react-router-dom';
import { Area, AreaChart, CartesianGrid, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { Gauge, Panel, SimChip, Stat, StatusText } from '../components/ui.jsx';
import { useStore } from '../core/store.js';
import { hardwareFault, lightingLoad, relayStatus } from '../core/logic.js';
import { CONTROLLERS, LIGHT_GROUPS, totalLamps } from '../core/config.js';

export const Chart = ({ data, keys, unit, height = 200 }) => (
  <ResponsiveContainer width="100%" height={height}>
    <AreaChart data={data} margin={{ left: -10, right: 8, top: 4 }}>
      <defs>{keys.map(([k, c]) => (<linearGradient key={k} id={`g${k}`} x1="0" y1="0" x2="0" y2="1"><stop offset="0%" stopColor={c} stopOpacity={0.5} /><stop offset="100%" stopColor={c} stopOpacity={0} /></linearGradient>))}</defs>
      <CartesianGrid stroke="#0f5a74" strokeOpacity={0.4} vertical={false} />
      <XAxis dataKey="t" tickFormatter={(t) => new Date(t).toLocaleTimeString([], { minute: '2-digit', second: '2-digit' })} stroke="#6fb3bf" fontSize={11} />
      <YAxis stroke="#6fb3bf" fontSize={11} domain={['auto', 'auto']} unit={unit} />
      <Tooltip contentStyle={{ background: '#06223a', border: '1px solid #0f5a74' }} labelFormatter={(t) => new Date(t).toLocaleTimeString()} formatter={(v) => v.toFixed(2)} />
      {keys.map(([k, c]) => <Area key={k} type="monotone" dataKey={k} stroke={c} fill={`url(#g${k})`} isAnimationActive={false} strokeWidth={2} />)}
    </AreaChart>
  </ResponsiveContainer>
);

export default function Dashboard() {
  const s = useStore();
  const { onCount, lamps, watts, unknown, unconfirmed, known } = lightingLoad(s.relays, s.controllers);
  const m = s.meter, sim = m?.simulated;
  const online = CONTROLLERS.filter((c) => s.controllers[c.id].online).length;
  const active = s.alarms.filter((a) => !a.ack);
  const hwFault = CONTROLLERS.filter((c) => hardwareFault(s.controllers[c.id].health)).length;
  const acUnknown = s.ac.contactor === null || s.ac.inputsValid === false;
  const acKind = acUnknown ? 'warn' : s.ac.contactor ? 'on' : 'off';
  return (
    <div className="grid" style={{ gap: 14 }}>
      {s.mode === 'sim' && <div className="banner">Simulation mode: all readings are generated by the in-browser simulator, not real meters. Switch to Live in Settings once hardware is connected.</div>}
      <div className="grid g6">
        <Panel className="stat"><Stat label="Lighting ON (confirmed)" value={known ? `${onCount}/31` : null} /><div className="meta" data-testid="lighting-unknown">{unknown} unknown{unconfirmed ? ` · ${unconfirmed} unconfirmed` : ''}</div></Panel>
        <Panel className="stat"><Stat label="Lamps lit" value={known ? `${lamps}/${totalLamps()}` : null} /></Panel>
        <Panel className="stat"><Stat label="Lighting load (rated)" value={known ? (watts / 1000).toFixed(1) : null} unit="kW" /></Panel>
        <Panel className="stat"><div className="l">AC status</div><div className="v" style={{ fontSize: 18 }}><StatusText kind={acKind}>{s.ac.inputsValid === false ? 'UNKNOWN (input fault)' : s.ac.contactor === null ? 'Not connected' : s.ac.contactor ? 'Running' : 'Stopped'}</StatusText></div></Panel>
        <Panel className="stat"><Stat label="Controllers" value={`${online}/2`} unit="online" /></Panel>
        <Panel className="stat"><Stat label="Active alarms" value={active.length} /></Panel>
      </div>
      <div className="grid g4">
        <Panel title="Power" right={<SimChip sim={sim} />}><Gauge value={m?.kw ?? null} max={10} unit="kW" label="Active power" /></Panel>
        <Panel title="Voltage L-N"><Gauge value={m?.vr ?? null} min={180} max={260} unit="V" label="Phase R" /></Panel>
        <Panel title="Current"><Gauge value={m?.ir ?? null} max={30} unit="A" label="Phase R" warnAbove={25} /></Panel>
        <Panel title="Metering" >
          <div className="grid g2">
            <Stat label="Frequency" value={m?.hz?.toFixed(2)} unit="Hz" />
            <Stat label="Power factor" value={m?.pf?.toFixed(2)} />
            <Stat label="Today" value={m ? s.energyToday.toFixed(2) : null} unit="kWh" />
            <Stat label="Est. cost" value={m ? (s.energyToday * s.tariff).toFixed(0) : null} />
          </div>
        </Panel>
      </div>
      <div className="grid g2">
        <Panel title="Live active power (kW)" right={<SimChip sim={sim} />}>
          {s.history.length ? <Chart data={s.history} keys={[['kw', '#22e6e6']]} /> : <p className="muted">Not connected: no meter telemetry received.</p>}
        </Panel>
        <Panel title="Controllers" right={<Link to="/controllers" className="chip">manage</Link>}>
          <table><tbody>{CONTROLLERS.map((c) => (
            <tr key={c.id}><td><StatusText kind={s.controllers[c.id].online ? 'on' : 'fault'}>{c.name}</StatusText></td><td className="muted">{c.id}</td>
              <td>{s.controllers[c.id].online ? 'Online' : 'Offline'}{hardwareFault(s.controllers[c.id].health) && <StatusText kind="fault"> · Hardware fault</StatusText>}</td></tr>))}</tbody></table>
          <h3 style={{ margin: '14px 0 6px', color: 'var(--cyan)', fontSize: 13 }}>RECENT ALARMS</h3>
          {active.slice(0, 4).map((a) => <div key={a.id}><StatusText kind={a.level === 'critical' ? 'fault' : 'warn'}>{a.text}</StatusText></div>)}
          {!active.length && <span className="muted">No active alarms</span>}
        </Panel>
      </div>
      <Panel title="Lighting by floor">
        <div className="grid g6">{[...new Set(LIGHT_GROUPS.map((g) => g.floor))].map((f) => {
          const gs = LIGHT_GROUPS.filter((g) => g.floor === f);
          const on = gs.filter((g) => relayStatus(s.relays[g.relay - 1], s.controllers[g.controller]) === 'CONFIRMED' && s.relays[g.relay - 1].state).length;
          return <Link key={f} to="/lighting" style={{ color: 'inherit', textDecoration: 'none' }}><Stat label={f} value={`${on}/${gs.length}`} unit="groups on" /></Link>;
        })}</div>
      </Panel>
    </div>
  );
}
